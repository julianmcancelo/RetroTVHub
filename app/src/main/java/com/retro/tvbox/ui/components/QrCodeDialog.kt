/**
 * 10-foot TV dialog displaying a high-contrast QR Code and direct local URL
 * for connecting smartphones as wireless gamepads.
 *
 * Optimized for Android TV navigation with direct D-Pad remote focus.
 *
 * @param serverUrl Local HTTP URL generated by PhoneControllerServer (e.g. "http://192.168.1.50:8080")
 * @param onDismissRequest Invoked when user presses Back, D-Pad Center or the Close button
 */
@Composable
fun QrCodeDialog(
    serverUrl: String,
    onDismissRequest: () -> Unit,
    modifier: Modifier = Modifier
) {
    val focusRequester = remember { FocusRequester() }

    // Generate QR Bitmap memoized by URL
    val qrBitmap = remember(serverUrl) {
        generateQrBitmap(serverUrl, 512)
    }

    // Auto-focus the close button on dialog presentation for D-pad remote
    LaunchedEffect(Unit) {
        focusRequester.requestFocus()
    }

    Dialog(
        onDismissRequest = onDismissRequest,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Box(
            modifier = Modifier
                .fillMaxSize()
                .background(Color(0xDF0C0E14))
                .onKeyEvent { keyEvent ->
                    if (keyEvent.key == Key.Back || keyEvent.key == Key.Escape) {
                        onDismissRequest()
                        true
                    } else {
                        false
                    }
                },
            contentAlignment = Alignment.Center
        ) {
            // Main Modal Card
            Box(
                modifier = modifier
                    .width(760.dp)
                    .clip(RoundedCornerShape(24.dp))
                    .background(Color(0xFF171A21))
                    .border(2.dp, Color(0xFF2C313D), RoundedCornerShape(24.dp))
                    .padding(36.dp)
            ) {
                Column(
                    horizontalAlignment = Alignment.CenterHorizontally,
                    modifier = Modifier.fillMaxWidth()
                ) {
                    // Header Section
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.Center,
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Box(
                            modifier = Modifier
                                .size(10.dp)
                                .clip(CircleShape)
                                .background(Color(0xFF00E676))
                        )
                        Spacer(modifier = Modifier.width(10.dp))
                        Text(
                            text = "CONECTAR MANDO VIRTUAL",
                            fontSize = 22.sp,
                            fontWeight = FontWeight.Black,
                            letterSpacing = 1.5.sp,
                            color = Color(0xFFF0F3F8)
                        )
                    }

                    Spacer(modifier = Modifier.height(6.dp))
                    Text(
                        text = "Juega con tu celular como control inalámbrico para 1 a 4 jugadores",
                        fontSize = 14.sp,
                        color = Color(0xFF8C93A4),
                        textAlign = TextAlign.Center
                    )

                    Spacer(modifier = Modifier.height(28.dp))

                    // Content Split: QR Code on Left, Instructions on Right
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        // Left: High contrast QR Code
                        Box(
                            modifier = Modifier
                                .size(240.dp)
                                .clip(RoundedCornerShape(16.dp))
                                .background(Color.White)
                                .padding(12.dp),
                            contentAlignment = Alignment.Center
                        ) {
                            if (qrBitmap != null) {
                                Image(
                                    bitmap = qrBitmap.asImageBitmap(),
                                    contentDescription = "Código QR para conectar control",
                                    modifier = Modifier.fillMaxSize()
                                )
                            }
                        }

                        Spacer(modifier = Modifier.width(28.dp))

                        // Right: Instructions & Direct URL
                        Column(
                            modifier = Modifier.weight(1f),
                            verticalArrangement = Arrangement.Center
                        ) {
                            InstructionStep(
                                number = "1",
                                title = "Conecta a la misma red Wi-Fi",
                                description = "El celular y la TV deben estar en la misma red local."
                            )

                            Spacer(modifier = Modifier.height(14.dp))

                            InstructionStep(
                                number = "2",
                                title = "Abre la cámara o el navegador",
                                description = "Escanea el código QR o ingresa manualmente a:"
                            )

                            Spacer(modifier = Modifier.height(10.dp))

                            // Direct URL Highlight Box
                            Box(
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .clip(RoundedCornerShape(10.dp))
                                    .background(Color(0xFF222733))
                                    .border(1.dp, Color(0xFF00D2FF).copy(alpha = 0.4f), RoundedCornerShape(10.dp))
                                    .padding(vertical = 10.dp, horizontal = 14.dp),
                                contentAlignment = Alignment.Center
                            ) {
                                Text(
                                    text = serverUrl,
                                    fontSize = 17.sp,
                                    fontWeight = FontWeight.Bold,
                                    fontFamily = FontFamily.Monospace,
                                    color = Color(0xFF00D2FF),
                                    letterSpacing = 0.5.sp
                                )
                            }

                            Spacer(modifier = Modifier.height(14.dp))

                            Text(
                                text = "✓ Compatible con iPhone y Android sin instalar ninguna app",
                                fontSize = 12.sp,
                                color = Color(0xFF00E676),
                                fontWeight = FontWeight.SemiBold
                            )
                        }
                    }

                    Spacer(modifier = Modifier.height(30.dp))

                    // Remote D-Pad focused Close Button
                    TvActionButton(
                        text = "LISTO / CERRAR  (Presiona OK)",
                        focusRequester = focusRequester,
                        onClick = onDismissRequest
                    )
                }
            }
        }
    }
}

